"""Opt-in frontend source coverage. Legacy indices and callers stay unchanged."""
from collections import Counter
from contextlib import closing
import hashlib
import json
from pathlib import PurePosixPath
import re
import sqlite3
import stat
from uuid import uuid4
import zipfile

from collect_gfi import materialized_archive_members
from gfi_prototype.common import sha256_file, sha256_text, utc_now
from gfi_prototype.retrieval import EvidenceStore, EXCLUDED_PARTS, TEXT_SUFFIXES
from gfi_prototype.research.retrieval import SnapshotRetriever

PROFILE='frontend_source_v1'
FRONTEND_SUFFIXES=frozenset({'.js','.jsx','.ts','.tsx'})
FRONTEND_EXCLUDED_PARTS=frozenset({'node_modules','vendor','vendors','third_party','third-party',
    'dist','build','coverage','out','.next','.nuxt','.cache','generated','__generated__'})
MAX_LINE_CHARS=2000
MAX_FILE_BYTES=1_000_000


def frontend_path_reason(path):
    if set(path.parts)&FRONTEND_EXCLUDED_PARTS:
        return 'frontend_generated_or_vendor_path'
    name=path.name.lower()
    if re.search(r'\.(?:min|bundle|chunk)\.(?:js|jsx|ts|tsx)$',name):
        return 'frontend_bundle_name'
    if re.search(r'[._-][0-9a-f]{8,}\.(?:js|jsx|ts|tsx)$',name):
        return 'frontend_hashed_asset_name'
    return None


def frontend_text_reason(text):
    # Inspect only a leading comment block, not string literals in source code.
    comments=[]
    for line in text[:4096].splitlines():
        stripped=line.strip()
        if not stripped or stripped.startswith('#!'):
            continue
        if not stripped.startswith(('//','/*','*')):
            break
        comments.append(stripped)
    if re.search(r'@generated|auto[- ]?generated|automatically generated|generated by|do not edit',
                 '\n'.join(comments),re.I):
        return 'frontend_generated_header'
    if any(len(line)>MAX_LINE_CHARS for line in text.splitlines()):
        return 'frontend_long_line_heuristic'
    return None


def source_kind(path):
    is_test=any(p in {'tests','_tests'} for p in path.parts) or path.name.startswith('test_')
    if path.suffix.lower() in FRONTEND_SUFFIXES:
        is_test=is_test or '__tests__' in path.parts or bool(re.search(r'\.(?:test|spec)\.[^.]+$',path.name))
    return 'test' if is_test else 'source' if path.suffix.lower() in FRONTEND_SUFFIXES or path.suffix=='.py' else 'document'


class FrontendEvidenceStore(EvidenceStore):
    def __init__(self,folder):
        super().__init__(folder)
        self.index=self.folder/'retrieval/source_index_frontend_v1.sqlite3'

    def build_index(self,on_progress=None):
        expected=self.folder/'retrieval/source_index_frontend_v1.sqlite3'
        if self.index!=expected:
            raise ValueError('Frontend profile must use its dedicated index path')
        notify=on_progress or (lambda message:None)
        notify('核验固定源码归档。')
        digest=sha256_file(self.archive)
        if digest!=self.snapshot['archive_sha256']:
            raise ValueError('Source archive checksum mismatch')
        policy={'profile':PROFILE,'suffixes':sorted(TEXT_SUFFIXES|FRONTEND_SUFFIXES),
                'frontend_excluded_parts':sorted(FRONTEND_EXCLUDED_PARTS),
                'max_line_chars':MAX_LINE_CHARS,'max_file_bytes':MAX_FILE_BYTES,
                'implementation_sha256':sha256_file(__file__)}
        policy_hash=sha256_text(json.dumps(policy,sort_keys=True))
        if self.index.exists():
            try:
                with closing(sqlite3.connect(self.index.resolve().as_uri()+'?mode=ro',uri=True)) as db:
                    meta=json.loads(db.execute('SELECT value FROM metadata WHERE key="index"').fetchone()[0])
                if (isinstance(meta,dict) and meta.get('archive_sha256')==digest and meta.get('policy_sha256')==policy_hash
                        and meta.get('repo')==self.repo and meta.get('commit_sha')==self.sha):
                    notify('复用JS/TS独立索引，旧索引不变。')
                    return {**meta,'reused':True}
            except (sqlite3.Error,ValueError,KeyError,TypeError):
                pass
        self.index.parent.mkdir(parents=True,exist_ok=True)
        temporary=self.index.with_name(self.index.name+'.'+uuid4().hex+'.building')
        db=sqlite3.connect(temporary)
        build_complete=False
        files=chunks=0
        by_suffix=Counter(); skipped=Counter()
        try:
            db.executescript('CREATE TABLE metadata(key TEXT PRIMARY KEY,value TEXT);'
                'CREATE TABLE chunks(path TEXT,start_line INTEGER,end_line INTEGER,text TEXT,file_sha256 TEXT,kind TEXT);'
                'CREATE VIRTUAL TABLE fts USING fts5(text,path,content="chunks",content_rowid="rowid");')
            with zipfile.ZipFile(self.archive) as archive:
                for relative,info in materialized_archive_members(archive,
                        preserve_missing_links=self.snapshot.get('missing_internal_link_handling')=='preserve_link_text'):
                    if info is None or stat.S_ISLNK(info.external_attr>>16):
                        continue
                    if relative!='/'.join(PurePosixPath(info.filename).parts[1:]):
                        continue
                    path=PurePosixPath(relative); suffix=path.suffix.lower()
                    if suffix not in TEXT_SUFFIXES|FRONTEND_SUFFIXES:
                        continue
                    if info.file_size>MAX_FILE_BYTES:
                        skipped['file_size_limit']+=1; continue
                    if (set(path.parts)&EXCLUDED_PARTS or path.name.startswith('.env')
                            or path.name.upper() in {'AGENTS.MD','CLAUDE.MD'}):
                        skipped['legacy_excluded_path']+=1; continue
                    reason=frontend_path_reason(path) if suffix in FRONTEND_SUFFIXES else None
                    if reason:
                        skipped[reason]+=1; continue
                    raw=archive.read(info)
                    try:text=raw.decode('utf-8')
                    except UnicodeDecodeError:
                        skipped['non_utf8']+=1; continue
                    if '\x00' in text:
                        skipped['binary_text']+=1; continue
                    reason=frontend_text_reason(text) if suffix in FRONTEND_SUFFIXES else None
                    if reason:
                        skipped[reason]+=1; continue
                    lines=text.splitlines()
                    if not lines:continue
                    files+=1; by_suffix[suffix]+=1
                    file_hash=hashlib.sha256(raw).hexdigest()
                    for first in range(0,len(lines),60):
                        last=min(first+80,len(lines)); excerpt='\n'.join(lines[first:last])
                        cursor=db.execute('INSERT INTO chunks VALUES(?,?,?,?,?,?)',
                            (relative,first+1,last,excerpt,file_hash,source_kind(path)))
                        db.execute('INSERT INTO fts(rowid,text,path) VALUES(?,?,?)',(cursor.lastrowid,excerpt,relative))
                        chunks+=1
                    if files%1000==0:
                        notify(f'已索引{files}个文件、{chunks}个片段。')
            meta={'profile':PROFILE,'index_version':1,'repo':self.repo,'commit_sha':self.sha,
                'archive_sha256':digest,'policy_sha256':policy_hash,'policy':policy,'built_at':utc_now(),
                'indexed_files':files,'indexed_chunks':chunks,'files_by_suffix':dict(by_suffix),
                'skipped':dict(skipped),'scope':'Pinned text source plus opt-in JS/TS; heuristic generated/vendor filters'}
            db.execute('INSERT INTO metadata VALUES(?,?)',('index',json.dumps(meta)))
            db.commit()
            build_complete=True
        finally:
            db.close()
            # A failed build must leave an existing valid index untouched.
            if not build_complete and temporary.exists():temporary.unlink()
        try:
            temporary.replace(self.index)
        finally:
            if temporary.exists():temporary.unlink()
        notify(f'独立索引完成：{files}个文件、{chunks}个片段。')
        return {**meta,'reused':False}


class FrontendSnapshotRetriever(SnapshotRetriever):
    """Explicit adapter; no existing research runner switches to it automatically."""
    def __init__(self,root,repo,max_evidence_chars=42000):
        super().__init__(root,repo,max_evidence_chars)
        self.store=FrontendEvidenceStore(self.folder)

    def initial(self,issue_number,issue_only=False):
        return {**super().initial(issue_number,issue_only),'retrieval_profile':PROFILE}
